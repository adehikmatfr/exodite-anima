def wr(path, text):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)


# ------------------------------------------------------------------ tokens
def tokens_doc():
    L = tl.resolve(TK, "light")
    D = tl.resolve(TK, "dark")
    rows = ""
    for name, spec in TK["semantic"].items():
        rows += f"| `{name}` | semantic | {spec['light'].split('color.')[1]} `{L[name]}` | {spec['dark'].split('color.')[1]} `{D[name]}` | {spec['use']} | stable |\n"
    prim = "".join(f"| `{n}` | primitive | `{val}` |\n" for n, val in TK["primitive"].items())
    mat = ""
    ok = 0
    for fg, bg, need, vals in tl.matrix(TK):
        passed = all(x >= need for x in vals)
        ok += passed
        mat += f"| `{fg}` on `{bg}` | {need}:1 | {vals[0]:.2f} | {vals[1]:.2f} | {'pass' if passed else 'FAIL'} |\n"
    typ = ""
    for n, s in TK["typography"].items():
        if n.startswith("type."):
            typ += f"| `{n}` | {TK['typography'][s['family']]} | {s['size']} / {s['line']} | {s['weight']} | {s['use']} |\n"
    sp = ", ".join(f"`{k}`" for k in TK["scale"]["space"])
    rad = ", ".join(f"`{k}` {v}" for k, v in TK["scale"]["radius"].items())
    dur = ", ".join(f"`{k}` {v} ms" for k, v in TK["scale"]["duration"].items())
    comp = "".join(f"| `{k}` | {v} |\n" for k, v in TK["component"].items())
    return f"""# Design tokens

Generated by `tools/gen_docs.py` from `design/library/tokens.json` (version {TK['version']}). **Do not edit by hand:** change the JSON, then regenerate. The `.pen` design files use the same JSON, and the Flutter theme must match it.

Direction: calm and minimal, warm neutral colours, one soft green accent, generous space. The journal text is the main content, so everything else stays quiet.

Modes: light and dark. High-contrast mode is not designed yet (open question in `context.md`).

## Tiers and naming
Three tiers (`design-token-authoring`): **primitive** (raw values), **semantic** (purpose, one value per mode), **component** (only where a component must differ from the semantic default). Screens use semantic or component tokens, never primitives. Names are lowercase and dot-separated, `category.property.role.variant`.

## Semantic colour tokens
| Token | Tier | Light | Dark | Use | Status |
|-------|------|-------|------|-----|--------|
{rows}
`color.border.default` is decorative only. Any control boundary uses `color.border.strong`, which meets 3:1.

## Contrast matrix (WCAG 2.2 AA, computed)
Text needs 4.5:1; control boundaries and focus rings need 3:1. {ok} of {len(tl.PAIRS)} pairs pass.

| Pair | Needed | Light | Dark | Result |
|------|--------|-------|------|--------|
{mat}
Disabled controls are exempt from the ratio but stay distinguishable by fill, border, and label. Colour never carries meaning alone: errors also have an icon and words, warnings have the word "Important", checked boxes have a tick.

## Typography
| Token | Font | Size / line height | Weight | Use |
|-------|------|--------------------|--------|-----|
{typ}
Both fonts are open source (SIL Open Font License) and may be bundled with the app; see `asset-register.md`. All sizes must scale with the system font size. The design previews cannot show every token faithfully (Lora is replaced by a fallback and Inter shows in one weight); `design-tokens.md` is the reference and the Flutter code implements it as written.

## Spacing, shape, motion, size
- Spacing scale: {sp}. Screen side margin {TK['scale']['screen']['margin']}.
- Radius: {rad}. Borders: hairline {TK['scale']['border']['hairline']} px, focus {TK['scale']['border']['focus']} px.
- Motion: {dur}. UI transitions stay at or under 300 ms and honour the system "reduce motion" setting. Screen design frame: {TK['scale']['screen']['width']} x {TK['scale']['screen']['height']}.
- No shadows: separation comes from surface colour and borders.

## Component tokens
| Token | Value |
|-------|-------|
{comp}
## Primitive tokens
| Token | Tier | Value |
|-------|------|-------|
{prim}
## Change process
A token change is proposed with name, reason, and affected components; classified patch (value tweak), minor (new token), or major (rename or removal); recorded in the changelog below; and announced to frontend-mobile with a migration note. Deleting a token is a breaking change (`design-system-governance`).

## Changelog
| Version | Date | Change |
|---------|------|--------|
| {TK['version']} | 2026-09-20 | Three tiers introduced; token names changed to `category.property.role`; new `color.border.strong` (3:1) because the old single border token measured about 1.4:1; new warning, pressed, focus, scrim tokens; contrast matrix computed. |
| 0.1.0 | 2026-09-20 | First flat token list (superseded). |
"""


