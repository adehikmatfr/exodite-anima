def screens_doc():
    idx = spec_index()
    out = ["""# Screen design specs (version 1)

Generated by `tools/gen_docs.py` from the screen table in that script and the acceptance criteria in the FEAT specs. Design files: `design/features/<area>/<area>-light.pen` and `-dark.pen`, exported previews in `design/exports/`. Tokens: `design-tokens.md`. Components: `component-specs.md`. Flows: `../../ux-design/report/user-flows.md`.

Status: draft, owner product-design, tokens 0.2.0. Every screen is drawn in every state listed. Screens are 390 x 844 (compact phone); tablets and landscape are not designed for version 1. Copy is draft and all strings must be externalised for translation. Numbers, dates, and counts on screen are illustrative.

Common to every screen: safe areas respected; primary action reachable by one thumb; all touch targets at least 48; error text always says what happened and what to do next; layout stays stable while loading; motion at most 300 ms and off under "reduce motion". Screens have no analytics events: the app collects none.
"""]
    for s in SCREENS:
        rows = ""
        n = 0
        for feat, acs in s["acs"]:
            for a in acs:
                crit, tc = idx.get((feat, f"AC-{a}"), ("(criterion not found)", "none"))
                n += 1
                rows += f"| AC-{n} | {crit} | {feat} AC-{a} | {tc} |\n"
        for crit, tc in A11Y_AC:
            n += 1
            rows += f"| AC-{n} | {crit} | design | {tc} |\n"
        if not s["acs"]:
            rows = "| none | No acceptance criterion exists for this state yet | none | none |\n" + rows
        out.append(f"""
## {s['id']} {s['name']}

| Field | Value |
|-------|-------|
| Screen | {s['id']} {s['name']} |
| Feature | {', '.join(s['feat']) if s['feat'] else 'none yet (see edge cases)'} |
| Status | draft |
| Design file | `design/features/{s['area']}/{s['area']}-light.pen` and `-dark.pen` |
| Flow context | {s['flow']} in `ux-design/report/user-flows.md` |

**Goal.** {s['goal']}

**States drawn.** {s['states']}.

**Reading and focus order.** {s['order']}

**Accessible names and announcements.** {s['names']}

**Edge cases.** {s['edge']}

**Open questions.** {s['oq']}

| AC | Criterion | Source | Test |
|----|-----------|--------|------|
{rows}""")
    return "".join(out)


