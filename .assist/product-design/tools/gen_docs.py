def spec_index():
    idx = {}
    for path in sorted(glob.glob(os.path.join(ASSIST, "product-manager", "features", "FEAT-*.md"))):
        t = open(path, encoding="utf-8").read()
        fid = re.search(r"^# (FEAT-\d{3})", t, re.M).group(1)
        for m in re.finditer(r"^\| (AC-\d+) \| (.*?) \| (.*?) \| (.*?) \| (TC-\d{3}) \|$", t, re.M):
            idx[(fid, m.group(1))] = (f"{m.group(2)}; {m.group(3)}; {m.group(4)}", m.group(5))
    return idx


